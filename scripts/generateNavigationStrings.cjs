const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const catalog = require('../src/configs/localization/navigationStrings.json');
const keys = Object.keys(catalog.es);
assert.deepEqual(Object.keys(catalog.en).sort(), [...keys].sort());
const literal = (value) => JSON.stringify(value);
const placeholders = (value) => [...new Set([...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]))];

const kotlin = keys.map(key => {
  const args = placeholders(catalog.es[key]);
  assert.deepEqual(placeholders(catalog.en[key]), args, key);
  const text = `(if (english) ${literal(catalog.en[key])} else ${literal(catalog.es[key])})`;
  return args.length
    ? `    fun ${key}(${args.map(name => `${name}: String`).join(', ')}): String = ${text}${args.map(name => `.replace("{${name}}", ${name})`).join('')}`
    : `    val ${key}: String get() = ${text}`;
}).join('\n');
const swift = keys.map(key => {
  const args = placeholders(catalog.es[key]);
  const text = `(english ? ${literal(catalog.en[key])} : ${literal(catalog.es[key])})`;
  return args.length
    ? `    func ${key}(${args.map(name => `${name}: String`).join(', ')}) -> String { ${text}${args.map(name => `.replacingOccurrences(of: "{${name}}", with: ${name})`).join('')} }`
    : `    var ${key}: String { ${text} }`;
}).join('\n');
const outputs = {
  'android/src/main/java/expo/modules/mapboxnavigation/NavigationStrings.kt': `// Generated by scripts/generateNavigationStrings.cjs. Edit src/configs/localization/navigationStrings.json.\npackage expo.modules.mapboxnavigation\n\nimport java.util.Locale\n\ninternal class NavigationStrings(locale: Locale = Locale("es")) {\n    private val english = locale.language.lowercase(Locale.ROOT) == "en"\n${kotlin}\n}\n`,
  'ios/NavigationStrings.swift': `// Generated by scripts/generateNavigationStrings.cjs. Edit src/configs/localization/navigationStrings.json.\nimport Foundation\n\nstruct NavigationStrings {\n    private let english: Bool\n    init(locale: Locale = Locale(identifier: "es")) { english = navigationLanguage(locale).lowercased() == "en" }\n${swift}\n}\n`,
};
for (const [relative, content] of Object.entries(outputs)) {
  const file = path.join(root, relative);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8'), content, `${relative} must be regenerated`);
  else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) fs.writeFileSync(file, content);
}
